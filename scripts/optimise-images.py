"""Generate WebP sizes for images referenced by portfolio content.

Run from any directory with Python and Pillow installed. Originals are retained;
the generated JS manifest is shared by cards, covers and gallery images.
"""
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
import json
from pathlib import Path
import re

from PIL import Image, ImageCms, ImageOps

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "src/js/imageVariants.js"
manifest_text = MANIFEST.read_text(encoding="utf-8") if MANIFEST.exists() else ""
previous = json.loads(manifest_text.split("export default ", 1)[1].rstrip(";\n")) if "Colour-managed variants v2" in manifest_text else {}
previous_time = MANIFEST.stat().st_mtime if MANIFEST.exists() else 0
SRGB = ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB"))
CONTENT = ROOT / "src/js/content"
sources = list(CONTENT.glob("*CaseStudy.js")) + [ROOT / "src/js/projectData.js"]
references = sorted({
    match
    for file in sources
    for match in re.findall(r'["\x27](img/[^"\x27]+\.(?:jpg|jpeg|png))["\x27]', file.read_text(encoding="utf-8"))
    if "/responsive/" not in match and "/optimised/" not in match
})


def optimise(relative):
    source = ROOT / relative
    cached = previous.get(relative)
    if cached and source.stat().st_mtime <= previous_time:
        generated = [item["src"] for item in cached.get("sources", [])] + [cached.get("thumbnail", relative)]
        if all((ROOT / item).exists() for item in generated):
            return relative, cached
    with Image.open(source) as raw:
        image = ImageOps.exif_transpose(raw)
        image = image.convert("RGBA" if "A" in image.getbands() or "transparency" in image.info else "RGB")
        # Photoshop exports can carry Adobe RGB or display profiles. Convert
        # their pixels to sRGB before removing metadata for the web version.
        profile = raw.info.get("icc_profile")
        if profile:
            alpha = image.getchannel("A") if image.mode == "RGBA" else None
            image = ImageCms.profileToProfile(image.convert("RGB"), ImageCms.ImageCmsProfile(BytesIO(profile)), SRGB, outputMode="RGB")
            if alpha is not None:
                image.putalpha(alpha)
        width, height = image.size
        result = {"width": width, "height": height}
        source_bytes = source.stat().st_size
        candidates = []
        # 480px serves the thumbnail strip as well as small screen candidates.
        for target_width in sorted({min(width, size) for size in (480, 800, 1600, 2400)}):
            target_height = round(height * target_width / width)
            resized = image.resize((target_width, target_height), Image.Resampling.LANCZOS)
            buffer = BytesIO()
            resized.save(buffer, format="WEBP", quality=88, method=4)
            data = buffer.getvalue()
            if len(data) >= source_bytes * .9:
                continue
            destination = source.parent / "optimised" / f"{source.stem}-{source.suffix[1:]}-{target_width}.webp"
            destination.parent.mkdir(exist_ok=True)
            destination.write_bytes(data)
            candidates.append({"src": destination.relative_to(ROOT).as_posix(), "width": target_width})
        if candidates:
            result["thumbnail"] = candidates[0]["src"]
            if candidates[-1]["width"] == min(width, 2400):
                result["src"] = candidates[-1]["src"]
            else:
                candidates.append({"src": relative, "width": width})
            result["sources"] = candidates
        return relative, result


if __name__ == "__main__":
    with ThreadPoolExecutor(max_workers=4) as pool:
        manifest = dict(pool.map(optimise, references))
    destination = ROOT / "src/js/imageVariants.js"
    destination.write_text("// Generated by scripts/optimise-images.py. Colour-managed variants v2. Do not edit by hand.\nexport default " + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    original_bytes = sum((ROOT / src).stat().st_size for src in manifest)
    fallback_bytes = sum((ROOT / entry.get("src", src)).stat().st_size for src, entry in manifest.items())
    small_bytes = sum((ROOT / min(entry.get("sources", [{"src": src, "width": entry["width"]}]), key=lambda candidate: abs(candidate["width"] - 800))["src"]).stat().st_size for src, entry in manifest.items())
    print(f"{len(manifest)} referenced images: original total {original_bytes / 1048576:.2f} MiB; large variants {fallback_bytes / 1048576:.2f} MiB; ~800px variants {small_bytes / 1048576:.2f} MiB.")
